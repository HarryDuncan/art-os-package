export const defaultFragmentLightId = (): string => {
  if (typeof crypto !== "undefined" && "randomUUID" in crypto) {
    return crypto.randomUUID().replace(/-/g, "");
  }
  return `id_${Date.now().toString(36)}_${Math.random().toString(36).slice(2, 10)}`;
};

export const getLightSlotParameterId = (
  light: ShaderEffectLightConfig,
  slotKey: FragmentLightSlotKey,
): string | undefined => light[slotKey]?.parameterId;

export const isParameterCompatibleWithSlot = (
  parameter: Pick<ParameterConfig, "valueType">,
  slotDef: FragmentLightSlotDefinition,
): boolean => slotDef.allowedValueTypes.includes(parameter.valueType);

export const createEmptyFragmentLight = (
  lightName: string,
  createId: () => string = defaultFragmentLightId,
): ShaderEffectLightConfig => ({
  id: createId(),
  name: lightName.trim() || "Light",
});

export const createParameterForSlot = (
  lightName: string,
  slotDef: FragmentLightSlotDefinition,
  createId: () => string = defaultFragmentLightId,
): ParameterConfig => {
  const guid = createId();
  const name = `${lightName.trim() || "Light"}_${slotDef.nameSuffix}`;
  return {
    guid,
    key: guid,
    name,
    type: "parameter",
    valueType: slotDef.allowedValueTypes[0] as ParameterConfig["valueType"],
    value: slotDef.defaultValue,
    parameterType:
      SHADER_PROPERTY_TYPES.UNIFORM as keyof typeof SHADER_PROPERTY_TYPES,
    autoGenerated: true,
    controlsConfig: slotDef.controlsConfig,
  };
};

export type PopulateFragmentLightResult = {
  light: ShaderEffectLightConfig;
  newParameters: ParameterConfig[];
};

/**
 * Fill empty slots on a light for the given group type.
 * Only creates parameters for slots that are not already bound.
 */
export const populateFragmentLightSlots = (
  light: ShaderEffectLightConfig,
  groupTypeId: FragmentLightGroupTypeId = FRAGMENT_LIGHT_GROUP_TYPE.STANDARD,
  createId: () => string = defaultFragmentLightId,
): PopulateFragmentLightResult => {
  const groupType =
    FRAGMENT_LIGHT_GROUP_TYPES[groupTypeId] ??
    FRAGMENT_LIGHT_GROUP_TYPES[FRAGMENT_LIGHT_GROUP_TYPE.STANDARD];

  const nextLight: ShaderEffectLightConfig = { ...light };
  const newParameters: ParameterConfig[] = [];

  for (const slotDef of groupType.slots) {
    if (getLightSlotParameterId(nextLight, slotDef.slotKey)) continue;
    const parameter = createParameterForSlot(nextLight.name, slotDef, createId);
    newParameters.push(parameter);
    nextLight[slotDef.slotKey] = { parameterId: parameter.guid };
  }

  return { light: nextLight, newParameters };
};

/** Collect all parameter guids currently referenced by a light's slots. */
export const collectLightParameterIds = (
  light: ShaderEffectLightConfig,
): string[] => {
  const ids: string[] = [];
  for (const slotKey of Object.values(FRAGMENT_LIGHT_SLOT)) {
    const id = getLightSlotParameterId(light, slotKey);
    if (id) ids.push(id);
  }
  return ids;
};

/** Ensure older configs without `id` get a stable id at load time. */
export const ensureFragmentLightId = (
  light: ShaderEffectLightConfig,
  createId: () => string = defaultFragmentLightId,
): ShaderEffectLightConfig => {
  if (light.id) return light;
  return { ...light, id: createId() };
};
