export type FragmentLightSlotKey =
  (typeof FRAGMENT_LIGHT_SLOT)[keyof typeof FRAGMENT_LIGHT_SLOT];

export type FragmentLightGroupTypeId =
  (typeof FRAGMENT_LIGHT_GROUP_TYPE)[keyof typeof FRAGMENT_LIGHT_GROUP_TYPE];

export type FragmentLightSlotDefinition = {
  slotKey: FragmentLightSlotKey;
  nameSuffix: string;
  allowedValueTypes: string[];
  defaultValue: unknown;
  controlsConfig: ParameterControlConfig;
};

export type FragmentLightGroupTypeDefinition = {
  id: FragmentLightGroupTypeId;
  label: string;
  slots: FragmentLightSlotDefinition[];
};

